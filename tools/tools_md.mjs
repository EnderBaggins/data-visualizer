#!/usr/bin/env node
// tools_md.mjs — writes TOOLS.md: every tool (core TOOL_DEFS in viewer/js/settings.js, and each plugin's registerTool)
// and every plugin "+ line" kind, from the same definitions the viewer's "?" list shows (v15.3). check.mjs fails when
// TOOLS.md is out of date:  node visualizer/tools/tools_md.mjs  writes it again.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const VIS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = p => fs.readFileSync(p, "utf8");
const str = (s, k) => (s.match(new RegExp(`\\b${k}:\\s*"((?:[^"\\\\]|\\\\.)*)"`)) || [])[1]?.replace(/\\"/g, '"') ?? "";
const WHERE = { any: "any plot", "1d": "1D plots", "2d": "maps", map: "maps whose axes are the quantity's space axes" };

/** The entries ({key, label, folder, where, help}) of the object literals that start with `{ key:` in text s. */
function entries(s) {
  return s.split(/\{\s*key:\s*/).slice(1).map(e => "key: " + e.slice(0, 1500)).map(e => ({
    key: (e.match(/^key:\s*"([^"]+)"/) || [])[1], label: str(e, "label"), folder: str(e, "folder"), where: str(e, "where"), help: str(e, "help") }));
}
export function toolsMarkdown() {
  const core = read(path.join(VIS, "viewer", "js", "settings.js"));
  const block = (core.match(/const TOOL_DEFS = \[([\s\S]*?)\n\]\.map/) || [])[1] || "";
  const rows = entries(block).map(t => ({ ...t, from: "core" }));
  const lineKinds = [];
  const pdir = path.join(VIS, "viewer", "plugins");
  for (const name of fs.existsSync(pdir) ? fs.readdirSync(pdir).sort() : []) {
    const dir = path.join(pdir, name);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const f of fs.readdirSync(dir).filter(f => f.endsWith(".js")).sort()) {
      const s = read(path.join(dir, f));
      for (const part of s.split("api.registerTool(").slice(1)) rows.push(...entries(part.slice(0, 2000)).slice(0, 1).map(t => ({ ...t, from: `plugin ${name}` })));
      for (const part of s.split("api.registerLineMenu(").slice(1)) lineKinds.push(...entries(part.slice(0, 2000)).slice(0, 1).map(t => ({ ...t, from: `plugin ${name}` })));
    }
  }
  const esc = x => String(x).replace(/\|/g, "\\|");
  const out = ["# Tools", "",
    "Generated by `node tools/tools_md.mjs` from the tool definitions (the same list as the viewer's **?** button). Do not",
    "edit by hand. Place a tool from the sidebar's **Tools** tab (drag it onto a plot, or click it and then a plot), or",
    "from the **?** list. How to use them by goal: `HOWTOUSE.md`.", "",
    "| Tool | Folder | Goes on | What it does | From |", "|---|---|---|---|---|",
    ...rows.map(t => `| **${esc(t.label)}** | ${t.folder} | ${WHERE[t.where] || t.where} | ${esc(t.help)} | ${t.from} |`), "",
    "## Line kinds from plugins (in a 1D plot's **+ line**)", "",
    "The core's kinds are: data, slope of…, rate of…, analytic.", "",
    "| Kind | What it draws | From |", "|---|---|---|",
    ...lineKinds.map(t => `| **${esc(t.label)}** | ${esc(t.help)} | ${t.from} |`), ""];
  return out.join("\n");
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(VIS, "TOOLS.md"), toolsMarkdown());
  console.log("wrote", path.join(VIS, "TOOLS.md"));
}
